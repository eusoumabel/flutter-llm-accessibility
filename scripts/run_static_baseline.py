#!/usr/bin/env python3
"""Run the traditional-tool baseline (O4) on every variant of the dataset.

Two tools from the Flutter ecosystem are run with the reference Flutter version
(ADR-R009, through ``fvm spawn``), in the project under baselines/flutter_static/:

- ``flutter analyze`` with the flutter_lints rule set, a purely static check;
- the accessibility guidelines of flutter_test (``androidTapTargetGuideline``,
  ``iOSTapTargetGuideline``, ``labeledTapTargetGuideline`` and
  ``textContrastGuideline``), evaluated in one widget test per variant. These tests
  render the widget, so they are not strictly static (ADR-R024).

Each component is built from the expression in baselines/flutter_static/harness.json.
Missing expressions are generated from the constructor (``--init-harness``) and can be
corrected by hand; edited entries are never overwritten.

A failed tap-target guideline is read as INT-01, a failed labeled-tap-target guideline
as SEM-01 and a failed contrast guideline as out of scope. The results are written to
results/baseline/static_tools.json and analysis/tables/static_baseline.md.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
from collections import defaultdict
from pathlib import Path

from build_pilot_review import load_samples
from calculate_metrics import add_prediction, empty_counts, load_ground_truth, with_scores

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT / "baselines" / "flutter_static"
HARNESS_PATH = PROJECT / "harness.json"
FLUTTER_VERSION = "3.41.8"  # ADR-R009
SAMPLES_OUT = PROJECT / "lib" / "samples"
TESTS_OUT = PROJECT / "test" / "generated"
RESULTS_PATH = ROOT / "results" / "baseline" / "static_tools.json"
TABLE_PATH = ROOT / "analysis" / "tables" / "static_baseline.md"

GUIDELINES = {
    "androidTapTargetGuideline": "INT-01",
    "iOSTapTargetGuideline": "INT-01",
    "labeledTapTargetGuideline": "SEM-01",
    "textContrastGuideline": "out_of_scope",
}

DEFAULTS = [
    (r"^VoidCallback\??$", "() {}"),
    (r"^(ValueChanged|ValueSetter)<.*>\??$", "(_) {}"),
    (r"^void Function\([^)]+\)\??$", "(_) {}"),
    (r"^void Function\(\)\??$", "() {}"),
    (r"^String\??$", "'Item'"),
    (r"^bool\??$", "false"),
    (r"^int\??$", "3"),
    (r"^double\??$", "24.0"),
    (r"^Widget\??$", "const SizedBox(width: 200, height: 120, child: Text('Content'))"),
    (r"^(List|Iterable)<String>\??$", "const ['One', 'Two', 'Three']"),
    (r"^ImageProvider\??$", "testImage"),
    (r"^Color\??$", "Colors.blue"),
    (r"^IconData\??$", "Icons.star"),
    (r"^TextEditingController\??$", "TextEditingController()"),
    (r"^TransformationController\??$", "TransformationController()"),
    (r"^PageController\??$", "PageController()"),
]

TEST_TEMPLATE = """// Generated by scripts/run_static_baseline.py. Do not edit.
import 'dart:typed_data';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_static_baseline/samples/{module}.dart';

final testImage = MemoryImage(Uint8List.fromList(const <int>[
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
  0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4,
  0x89, 0x00, 0x00, 0x00, 0x0B, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x60, 0x00, 0x02, 0x00,
  0x00, 0x05, 0x00, 0x01, 0x7A, 0x5E, 0xAB, 0x3F, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44,
  0xAE, 0x42, 0x60, 0x82,
]));

void main() {{
  testWidgets('{module}', (tester) async {{
    final handle = tester.ensureSemantics();
    await tester.pumpWidget(MaterialApp(home: Scaffold(body: Center(child: {expression}))));
    await tester.pump();
    final exception = tester.takeException();
    if (exception != null) {{
      // ignore: avoid_print
      print('A11Y|{module}|render_error|false|${{exception.toString().split('\\n').first}}');
    }}
    final guidelines = <String, AccessibilityGuideline>{{
      'androidTapTargetGuideline': androidTapTargetGuideline,
      'iOSTapTargetGuideline': iOSTapTargetGuideline,
      'labeledTapTargetGuideline': labeledTapTargetGuideline,
      'textContrastGuideline': textContrastGuideline,
    }};
    for (final entry in guidelines.entries) {{
      final result = await entry.value.evaluate(tester);
      final reason = result.reason?.replaceAll('\\n', ' ') ?? '';
      // ignore: avoid_print
      print('A11Y|{module}|${{entry.key}}|${{result.passed}}|$reason');
    }}
    handle.dispose();
  }});
}}
"""


def variants():
    for sample_id, (sample_dir, meta) in sorted(load_samples().items()):
        for variant, file_name in meta["files"].items():
            yield sample_id, variant, sample_dir / file_name


def guess_expression(source: str) -> str:
    """Build a constructor call from the public widget's required named parameters."""
    match = re.search(r"^class (\w+) extends (StatelessWidget|StatefulWidget)", source, re.M)
    if not match:
        return ""
    name = match.group(1)
    fields = {m.group(2): m.group(1).strip() for m in re.finditer(r"^\s+final (.+?) (\w+);", source, re.M)}
    enums = set(re.findall(r"^enum (\w+)", source, re.M))
    ctor = re.search(rf"{name}\(\s*\{{(.*?)\}}\s*\)", source, re.S)
    args = []
    for param in re.findall(r"required this\.(\w+)", ctor.group(1) if ctor else ""):
        type_name = fields.get(param, "")
        value = f"{type_name.rstrip('?')}.values.first" if type_name.rstrip("?") in enums else ""
        for pattern, default in DEFAULTS:
            if not value and re.match(pattern, type_name):
                value = default
        args.append(f"{param}: {value or 'TODO'}")
    return f"{name}({', '.join(args)})"


def init_harness(harness: dict) -> dict:
    for sample_id, variant, path in variants():
        key = f"{sample_id}_{variant}"
        if key not in harness:
            harness[key] = guess_expression(path.read_text(encoding="utf-8"))
    return dict(sorted(harness.items()))


def flutter(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["fvm", "spawn", FLUTTER_VERSION, *args], cwd=PROJECT, capture_output=True, text=True)


def generate(harness: dict):
    for directory in (SAMPLES_OUT, TESTS_OUT):
        shutil.rmtree(directory, ignore_errors=True)
        directory.mkdir(parents=True)
    for sample_id, variant, path in variants():
        module = f"{sample_id}_{variant}".lower()
        shutil.copy(path, SAMPLES_OUT / f"{module}.dart")
        expression = harness.get(f"{sample_id}_{variant}", "")
        test = TEST_TEMPLATE.format(module=module, expression=expression)
        (TESTS_OUT / f"{module}_test.dart").write_text(test, encoding="utf-8")


def run_analyze() -> dict:
    output = flutter("analyze", "--no-fatal-infos", "--no-fatal-warnings", "lib/samples")
    diagnostics = defaultdict(list)
    for line in output.stdout.splitlines():
        match = re.match(r"\s*(info|warning|error) • (.+) • lib/samples/(\w+)\.dart:(\d+):\d+ • (\S+)", line)
        if match:
            severity, message, module, line_no, rule = match.groups()
            diagnostics[module].append({"severity": severity, "rule": rule, "line": int(line_no), "message": message})
    return diagnostics


def run_tests() -> tuple[dict, dict]:
    output = flutter("test", "test/generated", "--reporter", "json")
    guidelines, failures = defaultdict(dict), {}
    tests = {}
    for line in output.stdout.splitlines():
        try:
            event = json.loads(line)
        except json.JSONDecodeError:
            continue
        if event.get("type") == "print" and event.get("message", "").startswith("A11Y|"):
            _, module, guideline, passed, reason = event["message"].split("|", 4)
            guidelines[module][guideline] = {"passed": passed == "true", "reason": reason.strip()}
        elif event.get("type") == "testStart":
            tests[event["test"]["id"]] = event["test"]["name"]
        elif event.get("type") == "error":
            name = tests.get(event.get("testID"), "")
            module = name.split()[-1] if name else ""
            failures[module or f"load_error_{len(failures)}"] = event.get("error", "").split("\n")[0]
    return guidelines, failures


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--init-harness", action="store_true", help="Only add missing harness entries and stop.")
    args = parser.parse_args()

    harness = json.loads(HARNESS_PATH.read_text(encoding="utf-8")) if HARNESS_PATH.exists() else {}
    harness = init_harness(harness)
    HARNESS_PATH.write_text(json.dumps(harness, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    todo = [key for key, value in harness.items() if not value or "TODO" in value]
    if args.init_harness:
        print(f"{len(harness)} harness entries, {len(todo)} to complete by hand: {', '.join(todo) or '-'}")
        return

    generate(harness)
    diagnostics = run_analyze()
    guidelines, failures = run_tests()

    truth = load_ground_truth()
    counts = defaultdict(empty_counts)
    caught = defaultdict(lambda: defaultdict(int))
    records = []
    for sample_id, variant, _ in variants():
        module = f"{sample_id}_{variant}".lower()
        results = guidelines.get(module, {})
        failed = sorted({GUIDELINES[g] for g, r in results.items() if g in GUIDELINES and not r["passed"]})
        in_scope = [code for code in failed if code != "out_of_scope"]
        complete = all(g in results for g in GUIDELINES)
        row = truth[(sample_id, variant)]
        pred = {"valid": complete, "predicted_has_violation": bool(in_scope)}
        add_prediction(counts["widget_test_guidelines"], row["has_violation"], pred)
        add_prediction(counts["flutter_analyze"], row["has_violation"], {"valid": True, "predicted_has_violation": False})
        if row["has_violation"]:
            principal = load_samples()[sample_id][1]["subcategory"]
            caught[principal]["total"] += 1
            caught[principal]["detected"] += bool(in_scope)
        records.append({
            "sample_id": sample_id, "variant": variant, "has_violation": row["has_violation"],
            "guidelines": results, "predicted": in_scope, "out_of_scope_failures": "out_of_scope" in failed,
            "test_error": failures.get(module, ""), "analyze": diagnostics.get(module, []),
        })

    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_PATH.write_text(json.dumps(records, indent=2, ensure_ascii=False), encoding="utf-8")

    rules = sorted({d["rule"] for r in records for d in r["analyze"]})
    lines = ["# Linha de base com ferramentas tradicionais (O4)", "",
             "| Ferramenta | VP | FP | VN | FN | Inválidas | Revocação | Precisão | F1 |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for tool, c in sorted(counts.items()):
        s = with_scores(c)
        lines.append(f"| {tool} | {s['tp']} | {s['fp']} | {s['tn']} | {s['fn']} | {s['invalid']} | "
                     f"{s['recall']:.2f} | {s['precision']:.2f} | {s['f1']:.2f} |")
    lines += ["", "## Violações detectadas pelos widget tests, por subcategoria principal", "",
              "| Subcategoria | Detectadas | Variantes com violação |", "| --- | --- | --- |"]
    for principal, c in sorted(caught.items()):
        lines.append(f"| {principal} | {c['detected']} | {c['total']} |")
    lines += ["", f"`flutter analyze` (flutter_lints) não tem regras de acessibilidade; regras disparadas: "
                  f"{', '.join(rules) or 'nenhuma'}. Ele é contado como sem detecção em todas as variantes.",
              f"Variantes cujo widget test não completou: {sum(1 for r in records if not r['guidelines'] or len(r['guidelines']) < len(GUIDELINES))}."]
    TABLE_PATH.parent.mkdir(parents=True, exist_ok=True)
    TABLE_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
